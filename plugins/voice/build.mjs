// 构建双产物：
//   lib/index.js  —— 宿主半边（Node，esm，ws 一并打包，零运行时依赖）
//   lib/client.js —— 浏览器半边（官方 client-modules 的 Lazy-CJS 工厂包裹格式，
//                    react 系 externals 走冻结的平台模块表）

import { build } from 'esbuild'
import { mkdirSync, writeFileSync } from 'node:fs'

mkdirSync('lib', { recursive: true })

await build({
  entryPoints: ['src/index.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  outfile: 'lib/index.js',
  external: ['bufferutil', 'utf-8-validate'],
  // ws（CJS）被打进 ESM 产物时需要运行期 require 解析 node 内建模块
  banner: { js: `import { createRequire as __voiceCreateRequire } from 'node:module'\nconst require = __voiceCreateRequire(import.meta.url)` },
  legalComments: 'none',
  logLevel: 'info',
})

const result = await build({
  entryPoints: ['src/client/index.tsx'],
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  jsx: 'automatic',
  loader: { '.css': 'text' },
  external: ['react', 'react/jsx-runtime', 'react-dom'],
  write: false,
  legalComments: 'none',
  logLevel: 'info',
})

const code = result.outputFiles[0].text
const wrapped = `// generated by build.mjs — do not edit
window.__ModuleLoader__.load({
  id: "dsh-yusheng-voice",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  }
});
`
writeFileSync('lib/client.js', wrapped)
console.log('lib/client.js written (%d bytes)', wrapped.length)

await build({
  entryPoints: { 'voice-client': 'src/client/voice-client.ts', 'demo-client': 'examples/avatar-client.ts' },
  bundle: true, platform: 'browser', format: 'esm', target: 'es2022', outdir: 'lib',
  legalComments: 'none', logLevel: 'info',
})
